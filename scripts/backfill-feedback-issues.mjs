#!/usr/bin/env node
/**
 * Backfill `feedback.issue_number` for reports filed before the column existed.
 *
 * Every issue the feedback relay has ever opened prints the row's UUID in its body
 * (`- **Feedback id:** \`…\``, see server/services/github.ts), so the mapping can be recovered
 * from GitHub alone — no guessing by title or timestamp. Newly created feedback records its
 * issue number directly and never needs this.
 *
 * Emits SQL rather than writing to D1 itself, so the statements can be read before they run:
 *
 *   GITHUB_TOKEN=… node scripts/backfill-feedback-issues.mjs > backfill.sql
 *   npx wrangler d1 execute mochi-class --remote --file=backfill.sql
 *
 * Re-running is harmless: every statement is an idempotent UPDATE by primary key.
 */

const REPO = process.env.FEEDBACK_REPO ?? 'VuNQ-Jeremy/calendar';
const token = process.env.GITHUB_TOKEN;

if (!token) {
  console.error('GITHUB_TOKEN is required (a token that can read issues on ' + REPO + ').');
  process.exit(1);
}

/** `- **Feedback id:** `2e13b34a-…`` — the only reliable link back to the row. */
const ID_RE = /\*\*Feedback id:\*\*\s*`([0-9a-fA-F-]{36})`/;

async function fetchIssues() {
  const out = [];
  for (let page = 1; ; page++) {
    const url =
      `https://api.github.com/repos/${REPO}/issues` +
      `?labels=feedback&state=all&per_page=100&page=${page}`;
    const res = await fetch(url, {
      headers: {
        Authorization: `token ${token}`,
        Accept: 'application/vnd.github+json',
        'User-Agent': 'mochi-feedback-backfill',
      },
    });
    if (!res.ok) throw new Error(`github ${res.status}: ${(await res.text()).slice(0, 200)}`);
    const batch = await res.json();
    out.push(...batch);
    if (batch.length < 100) return out;
  }
}

const issues = await fetchIssues();
const pairs = [];
const skipped = [];

for (const issue of issues) {
  // Pull requests come back from the issues endpoint too; they carry no feedback body.
  if (issue.pull_request) continue;
  const m = ID_RE.exec(issue.body ?? '');
  if (m) pairs.push({ number: issue.number, id: m[1] });
  else skipped.push(issue.number);
}

// Oldest issue wins if a row somehow has two (a retried create): the first one is the thread
// the brainstorm routine actually commented on.
pairs.sort((a, b) => a.number - b.number);
const seen = new Set();
const unique = pairs.filter((p) => !seen.has(p.id) && seen.add(p.id) !== false);

console.log('-- Generated by scripts/backfill-feedback-issues.mjs');
console.log(`-- ${unique.length} of ${issues.length} feedback-labelled issues matched a row id.`);
if (skipped.length) console.log(`-- No feedback id in the body of: #${skipped.join(', #')}`);
for (const p of unique) {
  console.log(`UPDATE feedback SET issue_number = ${p.number} WHERE id = '${p.id}';`);
}

console.error(`matched ${unique.length}, unmatched ${skipped.length}`);
